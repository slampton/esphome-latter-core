void lunar_disc_cache_drop() noexcept {
  auto &st = lunar_cache_state();
  for (auto &t : st.tiles) {
    if (t.px != nullptr) {
      ui_psram_free(t.px);
      t.px = nullptr;
    }
    t.cap_px = 0;
    t.r = -1;
    t.bucket = -1;
    t.last_use = 0;
  }
  if (st.scratch != nullptr) {
    ui_psram_free(st.scratch);
    st.scratch = nullptr;
  }
  st.scratch_w = 0;
  st.use_seq = 0;
}

void render_lunar_disc(Rgb565Surface &it, int moon_cx, int moon_cy, int moon_r, double cycle) {
  if (moon_r <= 0) return;

  const int bucket = lunar_phase_bucket(cycle);
  const LunarShade sh(moon_r, static_cast<double>(bucket) / LUNAR_PHASE_BUCKETS);
  const int dia = 2 * moon_r + 1;
  bool needs_shade = false;
  LunarDiscTile *tile = lunar_tile_acquire(moon_r, bucket, needs_shade);

  auto &st = lunar_cache_state();
  if (tile == nullptr && st.scratch_w < dia) {
    if (st.scratch != nullptr) ui_psram_free(st.scratch);
    st.scratch = static_cast<uint16_t *>(ui_psram_malloc(static_cast<size_t>(dia) * sizeof(uint16_t)));
    st.scratch_w = (st.scratch != nullptr) ? dia : 0;
    if (st.scratch == nullptr) return;
  }

  const uint16_t *fb = active_frame_buf16();
  const float r_in = sh.r_f - 0.90f;

  for (int my = -moon_r; my <= moon_r; my++) {
    const int py = moon_cy + my;
    const int w_line = lunar_aa_half_span(moon_r, my);
    const bool visible = row_in_clip_band(py);
    uint16_t *row;
    if (tile != nullptr) {
      row = tile->px + static_cast<size_t>(my + moon_r) * static_cast<size_t>(dia) + static_cast<size_t>(moon_r - w_line);
      if (needs_shade) shade_lunar_row(row, sh, my, w_line);
    } else {
      if (!visible) continue;
      row = st.scratch;
      shade_lunar_row(row, sh, my, w_line);
    }
    if (!visible) continue;

    const float my_sq_f = static_cast<float>(my * my);
    const float r_in_sq = (r_in > 0.0f) ? (r_in * r_in - my_sq_f) : -1.0f;
    const int s_in = (r_in_sq >= 0.0f) ? std::min(w_line, static_cast<int>(std::floor(std::sqrt(r_in_sq)))) : -1;

    auto blend_limb_px = [&](int mx) {
      const int px = moon_cx + mx;
      if (px < 0 || px >= SCREEN_W) return;
      const float edge_t = ((sh.r_f + 0.45f) - std::sqrt(static_cast<float>(mx * mx) + my_sq_f)) * (1.0f / 1.35f);
      if (edge_t <= 0.0f) return;
      const float edge_alpha = (edge_t >= 1.0f) ? 1.0f : (edge_t * edge_t * (3.0f - 2.0f * edge_t));
      const uint16_t m565 = row[mx + w_line];
      const int mr5 = (m565 >> 11) & 0x1F, mg6 = (m565 >> 5) & 0x3F, mb5 = m565 & 0x1F;
      const UiColor mc(static_cast<uint8_t>((mr5 << 3) | (mr5 >> 2)),
                       static_cast<uint8_t>((mg6 << 2) | (mg6 >> 4)),
                       static_cast<uint8_t>((mb5 << 3) | (mb5 >> 2)));
      UiColor bg_c = kChromeShadow;
      if (fb != nullptr) {
        const uint16_t p = decode_hw_rgb565_raw(fb[static_cast<size_t>(py) * SCREEN_W + static_cast<size_t>(px)]);
        const int br5 = (p >> 11) & 0x1F, bg6 = (p >> 5) & 0x3F, bb5 = p & 0x1F;
        bg_c = UiColor(static_cast<uint8_t>((br5 << 3) | (br5 >> 2)),
                       static_cast<uint8_t>((bg6 << 2) | (bg6 >> 4)),
                       static_cast<uint8_t>((bb5 << 3) | (bb5 >> 2)));
      }
      fast_pixel(it, px, py, mix_color_q8(bg_c, mc, static_cast<int>(std::round(edge_alpha * 256.0f))));
    };

    if (s_in >= 0) {
      for (int mx = -w_line; mx < -s_in; mx++) blend_limb_px(mx);
      blit_rgb565_scanline(it, moon_cx - s_in, py, 2 * s_in + 1, row + (w_line - s_in), false);
      for (int mx = s_in + 1; mx <= w_line; mx++) blend_limb_px(mx);
    } else {
      for (int mx = -w_line; mx <= w_line; mx++) blend_limb_px(mx);
    }
  }
}

