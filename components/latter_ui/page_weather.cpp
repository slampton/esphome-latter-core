// The shaded lunar disc depends only on its radius and the moon phase: the albedo LUT, limb
// darkening and terminator penumbra are independent of position, theme and wall-clock time.
static constexpr int LUNAR_PHASE_BUCKETS = 2048;

int lunar_phase_bucket(double cycle) {
  const double c = cycle - std::floor(cycle);
  return static_cast<int>(std::lround(c * LUNAR_PHASE_BUCKETS)) % LUNAR_PHASE_BUCKETS;
}

struct LunarShade {
  int r;
  float r_f;
  float r_sq;
  float inv_r;
  float sun_x;
  float sun_z;
  float term_w;
  float inv_term_w;
  float lit_scale;

  LunarShade(int moon_r, double cycle) : r(moon_r) {
    r_f = static_cast<float>(moon_r);
    r_sq = r_f * r_f;
    inv_r = (moon_r > 0) ? (1.0f / r_f) : 1.0f;
    const float angle = static_cast<float>(cycle * 2.0 * 3.1415926535);
    sun_x = fast_sin(angle);
    sun_z = -fast_cos(angle);
    term_w = (moon_r < 40) ? 0.18f : 0.13f;
    inv_term_w = 1.0f / term_w;
    const float illum_frac = 0.5f * (1.0f + sun_z);
    if (illum_frac <= 0.015f) {
      lit_scale = 0.0f;
    } else if (illum_frac >= 0.040f) {
      lit_scale = 1.0f;
    } else {
      const float u = (illum_frac - 0.015f) * (1.0f / 0.025f);
      lit_scale = u * u * (3.0f - 2.0f * u);
    }
  }
};

int lunar_aa_half_span(int moon_r, int my) {
  const float r_aa = static_cast<float>(moon_r) + 0.45f;
  const float d2 = r_aa * r_aa - static_cast<float>(my * my);
  if (d2 <= 0.0f) return 0;
  const int w = static_cast<int>(std::floor(std::sqrt(d2)));
  return (w > moon_r) ? moon_r : w;
}

void shade_lunar_row(uint16_t *row, const LunarShade &sh, int my, int w_line) {
  const int moon_r = sh.r;
  const float my_sq_f = static_cast<float>(my * my);
  const int two_r = 2 * std::max(1, moon_r);
  const int ty_139 = (moon_r == 69) ? (my + 69) : ((my + moon_r) * 138 / two_r);
  const uint8_t *const tex_row = LUNAR_ALBEDO_139[ty_139];
  const float r_outer = sh.r_f + 0.45f;
  const float r_outer_sq = r_outer * r_outer;
  // Hoist 138 / (2 * moon_r) to 16.16 fixed point so the inner pixel loop does zero integer divisions.
  const uint32_t tx_step_fp =
      (moon_r == 69) ? 0U : (((138U << 16) + static_cast<uint32_t>(two_r) - 1U) / static_cast<uint32_t>(two_r));
  uint32_t tx_fp = (moon_r == 69) ? 0U : (static_cast<uint32_t>(moon_r - w_line) * tx_step_fp);

  for (int mx = -w_line; mx <= w_line; mx++) {
    const float r2 = static_cast<float>(mx * mx) + my_sq_f;
    if (r2 >= r_outer_sq) {
      row[mx + w_line] = 0;
      tx_fp += tx_step_fp;
      continue;
    }

    uint8_t tex_u8;
    if (moon_r == 69) {
      tex_u8 = tex_row[mx + 69];
    } else {
      const int tx_139 = std::min<int>(138, static_cast<int>(tx_fp >> 16));
      tex_u8 = tex_row[tx_139];
      tx_fp += tx_step_fp;
    }

    const float mz = (r2 < sh.r_sq) ? std::sqrt(sh.r_sq - r2) : 0.0f;
    const float nz = mz * sh.inv_r;
    const float base_lum = static_cast<float>(tex_u8) * (0.84f + 0.16f * nz);

    float shadow = 0.0f;
    if (sh.lit_scale > 0.0f) {
      const float ndotl = (static_cast<float>(mx) * sh.sun_x + mz * sh.sun_z) * sh.inv_r;
      if (ndotl >= sh.term_w) {
        shadow = sh.lit_scale;
      } else if (ndotl > 0.0f) {
        const float t = ndotl * sh.inv_term_w;
        shadow = (t * t * (3.0f - 2.0f * t)) * sh.lit_scale;
      }
    }

    const float earthshine_limb = 0.62f + 0.38f * nz;
    const float dark_lum = (6.0f + static_cast<float>(tex_u8) * 0.115f) * earthshine_limb;

    const float lit_r = base_lum;
    const float lit_g = base_lum * 0.98f;
    const float lit_b = base_lum * 0.94f;

    const float drk_r = dark_lum * 0.82f;
    const float drk_g = dark_lum * 0.90f;
    const float drk_b = dark_lum * 1.12f;

    const uint8_t cr = static_cast<uint8_t>(std::fmin(255.0f, drk_r + (lit_r - drk_r) * shadow));
    const uint8_t cg = static_cast<uint8_t>(std::fmin(255.0f, drk_g + (lit_g - drk_g) * shadow));
    const uint8_t cb = static_cast<uint8_t>(std::fmin(255.0f, drk_b + (lit_b - drk_b) * shadow));
    row[mx + w_line] = static_cast<uint16_t>(((static_cast<uint16_t>(cr) & 0xF8U) << 8) |
                                             ((static_cast<uint16_t>(cg) & 0xFCU) << 3) |
                                             (static_cast<uint16_t>(cb) >> 3));
  }
}

struct LunarDiscTile {
  uint16_t *px = nullptr;
  size_t cap_px = 0;
  int r = -1;
  int bucket = -1;
  uint32_t last_use = 0;
};

struct LunarDiscCacheState {
  LunarDiscTile tiles[2]{};
  uint16_t *scratch = nullptr;
  int scratch_w = 0;
  uint32_t use_seq = 0;
};

LunarDiscCacheState &lunar_cache_state() noexcept {
  static LunarDiscCacheState st{};
  return st;
}

LunarDiscTile *lunar_tile_acquire(int r, int bucket, bool &needs_shade) {
  auto &st = lunar_cache_state();
  ++st.use_seq;
  needs_shade = false;
  for (auto &t : st.tiles) {
    if (t.px != nullptr && t.r == r && t.bucket == bucket) {
      t.last_use = st.use_seq;
      return &t;
    }
  }
  LunarDiscTile *victim = &st.tiles[0];
  bool same_r = false;
  for (auto &t : st.tiles) {
    if (t.px != nullptr && t.r == r) {
      victim = &t;
      same_r = true;
      break;
    }
  }
  if (!same_r && st.tiles[1].last_use < st.tiles[0].last_use) victim = &st.tiles[1];

  const size_t dia = static_cast<size_t>(2 * r + 1);
  const size_t need = dia * dia;
  if (victim->cap_px < need) {
    if (victim->px != nullptr) ui_psram_free(victim->px);
    victim->px = static_cast<uint16_t *>(ui_psram_malloc(need * sizeof(uint16_t)));
    victim->cap_px = (victim->px != nullptr) ? need : 0;
    if (victim->px == nullptr) {
      victim->r = -1;
      victim->bucket = -1;
      return nullptr;
    }
  }
  victim->r = r;
  victim->bucket = bucket;
  victim->last_use = st.use_seq;
  needs_shade = true;
  return victim;
}

