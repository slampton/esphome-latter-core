#!/usr/bin/env python3
"""Scaffold a new Latter board from its facts file, and generate bench bring-up probes.

Inputs come from boards/facts/<board_id>.json (see tools/check_boards.py and
boards/facts/schema.json). Standard library only.

Usage:
  python tools/new_board.py <board_id>                # board HAL + device + bring-up skeletons
  python tools/new_board.py <board_id> --out DIR      # write somewhere else (e.g. a scratch dir)
  python tools/new_board.py <board_id> --force        # overwrite existing files
  python tools/new_board.py --bringup                 # (re)generate examples/bringup/<id>.yaml for every board
  python tools/new_board.py --bringup --check         # fail if any committed bring-up probe is stale

Never overwrites an existing file without --force (the --bringup mode owns its generated files).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
FACTS_DIR = REPO / "boards" / "facts"
BRINGUP_DIR = REPO / "examples" / "bringup"

INPUT_ROLES = {"pwr_key", "touch_int", "imu_int1", "imu_int2", "rtc_int"}
SWITCH_ROLES = {"speaker_pa", "haptic_motor", "backlight_enable", "sd_power_gate"}
PWM_ROLES = {"backlight_pwm", "backlight_analog_dim"}
HAL_SCRIPTS = (
    ("hal_set_dac_mute", ("muted", "bool"), "Mute the codec output"),
    (
        "hal_set_audio_codecs_standby",
        ("standby", "bool"),
        "Codec low-power standby / wake",
    ),
    (
        "hal_release_deep_sleep_holds",
        None,
        "Release GPIO holds at boot; pulse touch reset if the driver cannot",
    ),
    (
        "hal_enter_hardware_hibernate",
        None,
        "Hold pins and cut power (called after state is saved)",
    ),
)


def load_facts(board_id: str) -> dict[str, Any]:
    path = FACTS_DIR / f"{board_id}.json"
    if not path.exists():
        sys.exit(
            f"error: {path.relative_to(REPO)} not found (write the facts file first: onboarding gate G1)"
        )
    return json.loads(path.read_text(encoding="utf-8"))


def is_p4(facts: dict[str, Any]) -> bool:
    return facts["silicon"]["soc"] == "ESP32-P4"


def beacon_lines(facts: dict[str, Any], minor: int) -> list[str]:
    """Area presence iBeacon (latter_beacon: VHCI on an on-chip controller, esp_hosted on the P4)."""
    del facts  # one component for every chip
    return ["latter_beacon:", "  id: ble_ctrl", '  uuid: "4C415454-4552-434F-5245-000000000220"',
            "  major: 1", f"  minor: {minor}"]


def pin_of(facts: dict[str, Any], role: str) -> int | None:
    for p in facts["pins"]:
        if p["role"] == role:
            return p["gpio"]
    return None


def slug(text: str) -> str:
    return (
        "".join(c if c.isalnum() else "-" for c in text.lower())
        .strip("-")
        .replace("--", "-")
    )


def esp32_block(facts: dict[str, Any], with_sdkconfig: bool = False) -> list[str]:
    flash = facts["silicon"].get("flash_mb", 16)
    sdkconfig = (
        [
            "    sdkconfig_options:",
            '      CONFIG_COMPILER_OPTIMIZATION_PERF: "y"',
            '      CONFIG_SPIRAM_MALLOC_ALWAYSINTERNAL: "256"',
            '      CONFIG_MBEDTLS_SSL_PROTO_TLS1_3: "y"',
        ]
        if with_sdkconfig
        else []
    )
    if is_p4(facts):
        return [
            "esp32:",
            "  variant: esp32p4",
            "  engineering_sample: ${p4_engineering_sample}",
            "  cpu_frequency: ${p4_cpu_frequency}",
            f"  flash_size: {flash}MB",
            "  framework:",
            "    type: esp-idf",
            *sdkconfig,
            "",
            "psram:",
            "  speed: 200MHz",
            "  ignore_not_found: false",
        ]
    return [
        "esp32:",
        "  board: esp32-s3-devkitc-1",
        f"  flash_size: {flash}MB",
        "  framework:",
        "    type: esp-idf",
        *sdkconfig,
        "",
        "psram:",
        "  mode: octal",
        "  speed: 80MHz",
        "  ignore_not_found: false",
    ]


def p4_substitutions(facts: dict[str, Any]) -> list[str]:
    if not is_p4(facts):
        return []
    return [
        '  # P4 silicon profile: rev3 -> "false" / 400MHz, rev1 -> "true" / 360MHz (binaries are not cross-compatible).',
        '  p4_engineering_sample: "false"',
        '  p4_cpu_frequency: "400MHz"',
    ]


def gpio_pin_lines(
    pin: dict[str, Any], indent: str, mode_lines: list[str]
) -> list[str]:
    lines = [f"{indent}pin:", f"{indent}  number: GPIO{pin['gpio']}"]
    if pin.get("polarity") == "active_low":
        lines.append(f"{indent}  inverted: true")
    lines += [f"{indent}  {m}" for m in mode_lines]
    if pin.get("strapping"):
        lines.append(f"{indent}  ignore_strapping_warning: true")
    return lines


def render_bringup(facts: dict[str, Any]) -> str:
    bid = facts["board_id"]
    lines: list[str] = [
        f"# AUTO-GENERATED by tools/new_board.py from boards/facts/{bid}.json. Do not edit by hand:",
        "# fix the facts file and run `python tools/new_board.py --bringup`.",
        "# ==============================================================================",
        f"# Bench bring-up probe: {facts['product']} ({facts['latter_device']})",
        "# No Latter core or GUI. Flash over USB, open the serial log, and attach it to the board PR as",
        "# onboarding gate G2 evidence. It logs:",
        "#   [BRINGUP:SILICON] / [BRINGUP:MEMORY]  revision, flash and PSRAM",
        "#   [BRINGUP:I2C]                          every facts-ledger I2C device present/missing, plus strays",
        "#   [BRINGUP:PMU]                          AXP2101 status, VBAT, gauge, rail enables (battery boards)",
        "#   key / interrupt edges                  press each key; touch the panel (touch INT pulses)",
        "# and exposes switches for each output net (amplifier, haptics, SD power, backlight).",
        "# Display, touch coordinates and audio are verified by the full firmware's [PROF:*] walk (gate G5).",
        "# ==============================================================================",
        "",
        "substitutions:",
        f'  name: "bringup-{slug(bid)}"',
        *p4_substitutions(facts),
        "",
        "esphome:",
        "  name: ${name}",
        f'  friendly_name: "Bring-up {facts["latter_device"]}"',
        "  includes:",
        "    - bringup.h",
        "  on_boot:",
        "    - priority: -100",
        "      then:",
        "        - lambda: 'latter_bringup::log_silicon();'",
        "        - delay: 1s",
        "        - script.execute: bringup_probe",
        "",
        *esp32_block(facts),
        "",
        "logger:",
        "  level: DEBUG",
    ]
    if is_p4(facts):
        lines.append("  hardware_uart: UART0")
    lines.append("")

    sda, scl = pin_of(facts, "i2c_sda"), pin_of(facts, "i2c_scl")
    addrs = [d["address"].lower() for d in facts.get("i2c_devices", [])]
    if sda is not None and scl is not None:
        lines += [
            "i2c:",
            "  - id: bus_internal",
            f"    sda: GPIO{sda}",
            f"    scl: GPIO{scl}",
            "    frequency: 100kHz",
            "    scan: false",
            "",
        ]
    pmu = facts["power"].get("pmu") == "AXP2101"

    lines += ["script:", "  - id: bringup_probe", "    then:", "      - lambda: |-"]
    if sda is not None and addrs:
        lines.append(
            f"          static const uint8_t expected[] = {{{', '.join(addrs)}}};"
        )
        lines.append(
            "          latter_bringup::probe_i2c(id(bus_internal), expected, sizeof(expected));"
        )
    if pmu:
        lines.append("          latter_bringup::log_axp2101(id(bus_internal));")
    if sda is not None and str(facts.get("latter_flags", {}).get("LATTER_HAS_RTC")) == "1":
        lines += [
            "          uint8_t rtc_reg = 0x04, rtc_buf[7] = {};",
            "          if (id(bus_internal).write_readv(0x51, &rtc_reg, 1, rtc_buf, sizeof(rtc_buf)) == esphome::i2c::ERROR_OK) {",
            '            ESP_LOGI("bringup", "[BRINGUP:RTC] pcf85063 os=%d bcd=20%02X-%02X-%02X %02X:%02X:%02X",',
            "                     (int)((rtc_buf[0] >> 7) & 1), rtc_buf[6], rtc_buf[5] & 0x1F, rtc_buf[3] & 0x3F,",
            "                     rtc_buf[2] & 0x3F, rtc_buf[1] & 0x7F, rtc_buf[0] & 0x7F);",
            "          }",
        ]
    if not (sda is not None and addrs) and not pmu:
        lines.append(
            '          ESP_LOGI("bringup", "[BRINGUP:I2C] no I2C bus in the facts");'
        )
    # Exercise each output net once so the bench log ties a visible/audible effect to a GPIO.
    for p in sorted(
        (p for p in facts["pins"] if p["role"] in SWITCH_ROLES), key=lambda x: x["gpio"]
    ):
        sid = f"out_gpio{p['gpio']}"
        lines += [
            "      - delay: 2s",
            f'      - logger.log: "[BRINGUP:OUT] {p["role"]} GPIO{p["gpio"]} HIGH for 1 s"',
            f"      - switch.turn_on: {sid}",
            "      - delay: 1s",
            f"      - switch.turn_off: {sid}",
        ]
    if any(p["role"] in PWM_ROLES for p in facts["pins"]):
        for pct in (10, 50, 100):
            lines += [
                "      - delay: 1s",
                f'      - logger.log: "[BRINGUP:OUT] backlight {pct} percent"',
                "      - light.turn_on:",
                "          id: backlight_light",
                f"          brightness: {pct}%",
            ]
    lines.append("")

    if pmu:
        lines += [
            "interval:",
            "  - interval: 10s",
            "    then:",
            "      - lambda: 'latter_bringup::log_axp2101(id(bus_internal));'",
            "",
        ]

    inputs = [
        p
        for p in facts["pins"]
        if p["role"] in INPUT_ROLES or p["role"].endswith("_button")
    ]
    if inputs:
        lines.append("binary_sensor:")
        for p in sorted(inputs, key=lambda x: x["gpio"]):
            pull = (
                ["mode:", "  input: true", "  pullup: true"]
                if p.get("polarity") in ("active_low", None)
                else ["mode:", "  input: true"]
            )
            name = f"{p['role']} GPIO{p['gpio']}"
            lines += [
                "  - platform: gpio",
                f'    name: "{name}"',
                *gpio_pin_lines(p, "    ", pull),
                "    on_state:",
                "      then:",
                "        - logger.log:",
                f'            format: "[BRINGUP:EDGE] {name} -> %s"',
                '            args: [\'x ? "ON" : "OFF"\']',
            ]
        lines.append("")

    outputs = [p for p in facts["pins"] if p["role"] in SWITCH_ROLES]
    if outputs:
        lines.append("switch:")
        for p in sorted(outputs, key=lambda x: x["gpio"]):
            label = (
                "SD power OFF (gate high)"
                if p["role"] == "sd_power_gate"
                else p["role"]
            )
            lines += [
                "  - platform: gpio",
                f"    id: out_gpio{p['gpio']}",
                f'    name: "{label} GPIO{p["gpio"]}"',
                *gpio_pin_lines({**p, "polarity": None}, "    ", []),
                "    restore_mode: ALWAYS_OFF",
            ]
        lines.append("")

    pwm = [p for p in facts["pins"] if p["role"] in PWM_ROLES]
    if pwm:
        hz = facts["latter_flags"].get("LATTER_BACKLIGHT_PWM_HZ", 2000)
        p = pwm[0]
        lines += [
            "output:",
            "  - platform: ledc",
            "    id: backlight_pwm",
            f"    pin: GPIO{p['gpio']}",
            f"    frequency: {hz}Hz",
        ]
        if p.get("polarity") == "inverted":
            lines.append("    inverted: true")
        lines += [
            "",
            "light:",
            "  - platform: monochromatic",
            "    id: backlight_light",
            '    name: "Backlight sweep"',
            "    output: backlight_pwm",
            "    restore_mode: ALWAYS_ON",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_board(facts: dict[str, Any]) -> str:
    bid = facts["board_id"]
    flags = facts["latter_flags"]
    hdr = [
        "# ==============================================================================",
        f'# Hardware Abstraction Layer (HAL): {facts["product"]} ("{facts["latter_device"]}")',
        f"# Scaffolded by tools/new_board.py from boards/facts/{bid}.json. Replace every TODO, then keep",
        "# python tools/check_boards.py green. Pin map:",
    ]
    for p in sorted(facts["pins"], key=lambda x: x["gpio"]):
        note = f" ({p['note']})" if p.get("note") else ""
        hdr.append(f"#   GPIO{p['gpio']:<3} {p['role']}{note} [{p['confidence']}]")
    hdr.append(
        "# =============================================================================="
    )
    body = [
        "",
        "substitutions:",
        # Full-duplex I2S bus rate; latter_mic is a resampler microphone down to audio_in_rate
        '  audio_out_rate: "48000"',
        '  audio_out_channels: "1"',
        '  audio_out_bits: "16"',
        '  audio_in_rate: "16000"',
        # micro_wake_word arena + weights in internal RAM: only with internal-RAM headroom (P4-class)
        f'  mww_internal_ram: "{"true" if "P4" in facts.get("silicon", {}).get("soc", "") else "false"}"',
    ]
    if pin_of(facts, "imu_int1") is not None:
        body.append(f"  imu_int1_pin: GPIO{pin_of(facts, 'imu_int1')}")
    body += p4_substitutions(facts)
    body += [
        "",
        "esphome:",
        "  build_flags:",
        f"    - '-DLATTER_BOARD_ID=\\\"{bid}\\\"'",
    ]
    if facts.get("ble_minor") is not None:
        body.append(f'    - "-DLATTER_BLE_MINOR={facts["ble_minor"]}"')
    body += [f'    - "-D{k}={v}"' for k, v in flags.items()]
    body += ["", *esp32_block(facts, with_sdkconfig=True), ""]
    sda, scl = pin_of(facts, "i2c_sda"), pin_of(facts, "i2c_scl")
    if sda is not None:
        body += [
            "i2c:",
            "  - id: bus_internal",
            f"    sda: GPIO{sda}",
            f"    scl: GPIO{scl}",
            "    frequency: 400kHz",
            "    scan: false",
            "",
        ]
    pkg_lines = [
        "packages:",
        f"  latter_chip: !include ../modules/hal/{'chip_esp32p4' if is_p4(facts) else 'chip_esp32s3'}.yaml",
    ]
    if str(flags.get("LATTER_HAS_IMU")) == "1":
        pkg_lines.append("  latter_imu: !include ../modules/hal/imu_qmi8658.yaml")
    if facts["power"].get("pmu") == "AXP2101":
        pkg_lines.append("  latter_pmu: !include ../modules/hal/pmu_axp2101.yaml")
    body += [
        "# TODO display: id disp1, full-frame PSRAM buffer (docs/porting-hardware.md section 1).",
        "# TODO touchscreen: id touch_screen, interrupt-driven if INT is routed.",
        "# TODO audio: include ../modules/hal/audio_es8311_duplex.yaml or audio_es8311_es7210_duplex.yaml",
        "#      (or define one i2s_audio bus with full_duplex: true, latter_mic_i2s + resampler latter_mic,",
        "#      physical_speaker, speaker_enable, and codecs at audio_out_rate).",
        "# TODO binary_sensor boot_button (and pwr_key on AXP2101 boards).",
        "",
        *pkg_lines,
        "",
        "script:",
    ]
    for sid, param, purpose in HAL_SCRIPTS:
        body += [f"  - id: {sid}", "    mode: restart"]
        if param:
            body += ["    parameters:", f"      {param[0]}: {param[1]}"]
        body += ["    then:", f"      - lambda: '(void)0;  // TODO: {purpose}'"]
    return "\n".join(hdr + body).rstrip("\n") + "\n"


def render_device(facts: dict[str, Any]) -> str:
    dev = slug(facts["latter_device"])
    bid = facts["board_id"]
    minor = facts.get("ble_minor", "TODO")
    stationary = str(facts["latter_flags"].get("LATTER_IS_STATIONARY")) == "1"
    return "\n".join(
        [
            "# ==============================================================================",
            f"# {facts['latter_device']} on {facts['product']}",
            f"# Scaffolded by tools/new_board.py from boards/facts/{bid}.json.",
            "# Repository: https://github.com/slampton/esphome-latter-core",
            "# ==============================================================================",
            "",
            "substitutions:",
            f'  name: "{dev}"',
            f'  friendly_name: "{facts["latter_device"]}"',
            '  version: "TODO"',
            f'  api_reboot_timeout: "{"15min" if stationary else "0s"}"',
            "",
            "external_components:",
            "  - source:",
            "      type: git",
            "      url: https://github.com/slampton/esphome-latter-core",
            "      ref: main",
            "    components: [latter_core, latter_ui, latter_beacon]",
            "    refresh: 0s",
            "",
            "esphome:",
            "  name: ${name}",
            "  friendly_name: ${friendly_name}",
            "  min_version: TODO  # match the other devices/*.yaml (latter-verify lockstep)",
            "  project:",
            f'    name: "slampton.{dev}"',
            '    version: "${version}"',
            "",
            "update:",
            "  - platform: http_request",
            "    id: latter_firmware_update",
            '    name: "Project Firmware"',
            f'    source: "https://slampton.github.io/esphome-latter-core/manifests/{dev}.json"',
            "    update_interval: never",
            "",
            "wifi:",
            "  id: wifi_ctrl",
            "",
            *beacon_lines(facts, minor),
            "",
            "improv_serial:",
            "",
            "packages:",
            f"  hal: !include ../boards/{bid}.yaml",
            "  latter_firmware: !include ../modules/latter_display_firmware.yaml",
            "",
        ]
    )


def write(path: Path, text: str, force: bool) -> None:
    if path.exists() and not force:
        print(f"skip   {path} (exists; use --force)")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote  {path}")


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "board_id", nargs="?", help="board id with a boards/facts/<id>.json file"
    )
    ap.add_argument(
        "--out", type=Path, default=REPO, help="output root (default: the repository)"
    )
    ap.add_argument("--force", action="store_true", help="overwrite existing files")
    ap.add_argument(
        "--bringup",
        action="store_true",
        help="generate examples/bringup/<id>.yaml for every board",
    )
    ap.add_argument(
        "--check", action="store_true", help="with --bringup: fail on stale probes"
    )
    args = ap.parse_args()

    if args.bringup:
        stale = []
        for f in sorted(FACTS_DIR.glob("*.json")):
            if f.name == "schema.json":
                continue
            facts = json.loads(f.read_text(encoding="utf-8"))
            target = BRINGUP_DIR / f"{facts['board_id']}.yaml"
            text = render_bringup(facts)
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if args.check:
                if current != text:
                    stale.append(str(target.relative_to(REPO)))
            elif current != text:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote  {target.relative_to(REPO)}")
        if stale:
            print(
                "ERROR stale bring-up probes (run python tools/new_board.py --bringup): "
                + ", ".join(stale)
            )
            return 1
        return 0

    if not args.board_id:
        ap.error("board_id is required unless --bringup is given")
    facts = load_facts(args.board_id)
    out = args.out.resolve()
    write(out / "boards" / f"{args.board_id}.yaml", render_board(facts), args.force)
    write(
        out / "devices" / f"{slug(facts['latter_device'])}.yaml",
        render_device(facts),
        args.force,
    )
    write(
        out / "examples" / "bringup" / f"{args.board_id}.yaml",
        render_bringup(facts),
        args.force,
    )
    print(
        "next: replace the TODOs, add a release.yml job, then run python tools/check_boards.py"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
